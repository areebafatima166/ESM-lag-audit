library(openesm); library(dplyr); library(lme4); library(lmerTest)
source('fried_0006_analysis.R')
boot_terms <- c('prev_x', 'prev_y', 'dirrev:prev_x', 'dirrev:prev_y')
boot_once <- function(d) { ids <- unique(d$id); picked <- sample(ids, length(ids), replace = TRUE)
  b <- bind_rows(lapply(seq_along(picked), function(i) d[d$id == picked[i], ] %>% mutate(id = i)))
  fit <- suppressWarnings(lmer(y_pmc ~ dir * (prev_x + prev_y) + x_pmc + x_mean + factor(beep) + (0 + x_pmc | id), data = b, REML = FALSE))
  c(fixef(fit)[boot_terms], singular = isSingular(fit)) }
dir.create('results', showWarnings = FALSE)
set.seed(2026)
boot6_raw <- t(replicate(1000, tryCatch(boot_once(dat6_both3), error = function(e) rep(NA_real_, length(boot_terms) + 1))))
colnames(boot6_raw) <- c(boot_terms, 'singular')
saveRDS(boot6_raw, 'results/boot6_raw.rds')
ci6 <- apply(boot6_raw[, boot_terms], 2, quantile, probs = c(0.025, 0.975), na.rm = TRUE)
write.csv(as.data.frame(t(ci6)), 'results/bootstrap6_ci.csv')
